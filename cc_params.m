function p = cc_params()
% 定速巡航模糊控制 —— 全局参数
%
% 被控对象：整车纵向动力学，只有一条力平衡方程
%              m * dv/dt = F_d - (滚动阻力 + 空气阻力 + 坡道阻力)
% 控制目标：让车速跟踪驾驶员设定的目标车速（定速巡航）

%% 整车参数（1.5 t 家用轿车）
p.m   = 1500;          % 整车质量 [kg]
p.g   = 9.81;          % 重力加速度 [m/s^2]
p.f   = 0.015;         % 滚动阻力系数
p.rho = 1.225;         % 空气密度 [kg/m^3]
p.Cd  = 0.32;          % 空气阻力系数
p.A   = 2.2;           % 迎风面积 [m^2]

%% 动力总成：油门开度 -> 驱动力（一阶惯性）
p.Fmax = 3000;         % 最大驱动力 [N]
p.tau  = 0.3;          % 动力总成响应时间常数 [s]

%% 模糊控制器参数
p.Ts  = 0.1;           % 控制器采样周期 [s]
p.Ke  = 1.0;           % 误差量化因子（e 的满量程约 1 m/s）
p.Kec = 1.5;           % 误差变化率量化因子（提供阻尼，抑制振荡）
p.Ku  = 0.10;          % 输出比例因子（每个采样周期最多动多少油门）

%% 工况（跑之前手动改这两个常数）
p.v_ref = 22.22;       % 设定车速 80 km/h [m/s]
p.grade = 0.05;        % 坡道坡度：0 = 平路，0.05 = 5% 上坡

p.Tend = 30;           % 单次仿真时长 [s]
p.dt   = 1e-3;         % 仿真步长 [s]

%% 初始状态：平路 80 km/h 巡航的平衡点
p.Fr0    = p.m*p.g*p.f + 0.5*p.rho*p.Cd*p.A*p.v_ref^2;  % 平路阻力 [N]
p.alpha0 = p.Fr0 / p.Fmax;                             % 所需油门开度
p.Fd0    = p.Fmax * p.alpha0;                          % 所需驱动力 [N]

end
